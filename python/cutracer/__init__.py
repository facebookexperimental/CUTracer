"""
CUTracer Python SDK

This package provides tools for validating, parsing, and analyzing
CUDA trace data generated by CUTracer.
"""

from __future__ import annotations

from importlib.metadata import PackageNotFoundError, version
from typing import Any

try:
    __version__ = version("cutracer")
except PackageNotFoundError:
    __version__ = "0+unknown"  # Development mode or not installed

_VALIDATION_EXPORTS = (
    "compare_trace_formats",
    "validate_json_trace",
    "validate_text_trace",
)


def __getattr__(name: str) -> Any:
    """Load validation helpers only when the full SDK surface requests them."""
    if name not in _VALIDATION_EXPORTS:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")

    from importlib import import_module

    try:
        validation = import_module("cutracer.validation")
    except ModuleNotFoundError as exc:
        if exc.name != "cutracer.validation":
            raise
        raise AttributeError(
            f"{name!r} requires the complete CUTracer SDK, not the "
            "pure service_contracts target"
        ) from None

    value = getattr(validation, name)
    globals()[name] = value
    return value


__all__ = [
    "__version__",
    *_VALIDATION_EXPORTS,
]
